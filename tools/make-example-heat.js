#!/usr/bin/env node
/*
 * Write example-heat.js: the ancestry heat the sandbox draws for level 2 at the
 * page's default seed 3, by DRIVING THE PAGE in the fake DOM — so the example
 * is the page's own output, reproduced by tests/example-heat.test.js.
 *   node tools/make-example-heat.js           write example-heat.js
 */
"use strict";
const fs = require("fs");
const path = require("path");
const { runPage } = require("./sandbox-drive.js");

const CONFIG = { level: "2", seed: 3 };

function build() {
  const p = runPage({ level: CONFIG.level, seed: CONFIG.seed });
  if (p.error) throw new Error(`the page refused the example run: ${p.error}`);
  const model = p.page.Sandbox.heat();
  if (!model) throw new Error("the page drew no heat for the example run");
  return JSON.parse(JSON.stringify({ config: CONFIG, fate: p.fate, model }));
}

if (require.main === module) {
  const out = path.join(__dirname, "..", "example-heat.js");
  fs.writeFileSync(
    out,
    "/* generated by tools/make-example-heat.js from the page's own level 2, seed 3 run; do not edit */\n" +
      `window.ExampleHeat = ${JSON.stringify(build())};\n`,
  );
  console.log(`wrote ${out}`);
}
module.exports = { build, CONFIG };
